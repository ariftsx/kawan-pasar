// Builds the CSS outputs of @kawan-pasar/tokens with Style Dictionary 5 (docs 11 §3):
//   dist/tokens.css: runtime variables `--kp-*`, Light on :root, Dark on [data-theme="dark"] and
//                    on prefers-color-scheme: dark unless the page forces light.
//   dist/theme.css:  Tailwind v4 `@theme inline` mapping, e.g. `--color-bg-brand: var(--kp-color-bg-brand)`.
// Theme names differ from runtime names on purpose: `--color-x: var(--color-x)` would be circular.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import StyleDictionary from 'style-dictionary';
import { formats, transforms } from 'style-dictionary/enums';

const SOURCE = new URL('../src/tokens/', import.meta.url);
const DIST = new URL('../dist/', import.meta.url);
const SOURCES = ['primitives', 'semantic', 'scale'];
const PRIMITIVE_GROUPS = new Set([
  'green',
  'neutral',
  'red',
  'blue',
  'amber',
  'purple',
  'slate',
  'orange',
  'teal',
]);
const HEADER = '/* Generated by @kawan-pasar/tokens — do not edit. */\n';

/** @typedef {Record<string, unknown>} Tree */

/** @returns {Promise<Tree>} */
async function loadTokens() {
  const trees = await Promise.all(
    SOURCES.map(async (name) => {
      /** @type {Tree} */
      const tree = JSON.parse(await readFile(new URL(`${name}.tokens.json`, SOURCE), 'utf8'));
      delete tree.$description;
      return tree;
    }),
  );
  const [primitives = {}, semantic = {}, scale = {}] = trees;
  return {
    ...scale,
    color: { .../** @type {Tree} */ (primitives.color), .../** @type {Tree} */ (semantic.color) },
  };
}

/** Replaces `$value` with the dark extension wherever one exists. */
function toDark(/** @type {unknown} */ node) {
  if (typeof node !== 'object' || node === null) return node;
  /** @type {Tree} */
  const copy = Object.fromEntries(Object.entries(node).map(([key, child]) => [key, toDark(child)]));
  const dark = /** @type {{ 'kp.theme'?: { dark?: string } } | undefined} */ (copy.$extensions)?.[
    'kp.theme'
  ]?.dark;
  return dark === undefined ? copy : { ...copy, $value: dark };
}

/** @param {{ path: string[] }} token */
const isPrimitive = (token) =>
  token.path[0] === 'color' && PRIMITIVE_GROUPS.has(token.path[1] ?? '');
/** @param {{ path: string[] }} token */
const isSemanticColor = (token) => token.path[0] === 'color' && !isPrimitive(token);

/**
 * @param {Tree} tokens
 * @param {string} selector
 * @param {(token: { path: string[] }) => boolean} filter
 * @returns {Promise<string>}
 */
async function cssBlock(tokens, selector, filter) {
  const sd = new StyleDictionary(
    {
      tokens: /** @type {import('style-dictionary/types').DesignTokens} */ (tokens),
      log: { verbosity: 'silent' },
      platforms: {
        css: {
          prefix: 'kp',
          transforms: [transforms.attributeCti, transforms.nameKebab, transforms.colorCss],
          files: [
            {
              destination: 'tokens.css',
              format: formats.cssVariables,
              filter,
              options: { selector, outputReferences: false, showFileHeader: false },
            },
          ],
        },
      },
    },
    { verbosity: 'silent' },
  );
  const [file] = await sd.formatPlatform('css');
  return String(file?.output ?? '').trim();
}

/** @param {string} block */
const indent = (block) => block.replace(/^/gm, '  ');

export async function buildCss() {
  const tokens = await loadTokens();
  const dark = /** @type {Tree} */ (toDark(tokens));
  const light = await cssBlock(tokens, ':root', (token) => !isPrimitive(token));
  const darkExplicit = await cssBlock(dark, '[data-theme="dark"]', isSemanticColor);
  const darkSystem = await cssBlock(dark, ':root:not([data-theme="light"])', isSemanticColor);
  const reducedMotion =
    ':root {\n  --kp-motion-fast: 0ms linear;\n  --kp-motion-base: 0ms linear;\n  --kp-motion-slow: 0ms linear;\n}';

  const tokensCss = [
    HEADER + light,
    darkExplicit,
    `@media (prefers-color-scheme: dark) {\n${indent(darkSystem)}\n}`,
    `@media (prefers-reduced-motion: reduce) {\n${indent(reducedMotion)}\n}`,
  ].join('\n\n');
  return { tokensCss: `${tokensCss}\n`, themeCss: themeCss(tokens) };
}

/** Tailwind v4 theme mapping; utilities become `bg-bg-brand`, `rounded-lg`, `shadow-1`, … */
function themeCss(/** @type {Tree} */ tokens) {
  const semantic = Object.entries(/** @type {Tree} */ (tokens.color)).filter(
    ([group]) => !group.startsWith('$') && !PRIMITIVE_GROUPS.has(group),
  );
  const colors = semantic.flatMap(([group, leaves]) =>
    Object.keys(/** @type {Tree} */ (leaves))
      .filter((name) => !name.startsWith('$'))
      .map((name) => `  --color-${group}-${name}: var(--kp-color-${group}-${name});`),
  );
  const named = (
    /** @type {unknown} */ subtree,
    /** @type {string} */ group,
    /** @type {string} */ themeName,
  ) =>
    Object.keys(/** @type {Tree} */ (subtree))
      .filter((name) => !name.startsWith('$'))
      .map((name) => `  --${themeName}-${name}: var(--kp-${group}-${name});`);
  const lines = [
    '  --color-*: initial;',
    ...colors,
    '  --spacing: 4px;',
    '  --radius-*: initial;',
    ...named(tokens.radius, 'radius', 'radius'),
    '  --shadow-*: initial;',
    ...named(tokens.elevation, 'elevation', 'shadow'),
    '  --breakpoint-*: initial;',
    '  --breakpoint-sm: 360px;',
    '  --breakpoint-md: 768px;',
    '  --breakpoint-lg: 1024px;',
    '  --breakpoint-xl: 1440px;',
  ];
  return `${HEADER}@theme inline {\n${lines.join('\n')}\n}\n\n@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { tokensCss, themeCss: theme } = await buildCss();
  await mkdir(DIST, { recursive: true });
  await writeFile(new URL('tokens.css', DIST), tokensCss);
  await writeFile(new URL('theme.css', DIST), theme);
}
